#!/usr/bin/env python3
"""Generates bridge/src/bk_asset_names.inc from the Banjo-Kazooie decompilation.

The decomp (CC0) names every asset in `enum asset_e` (include/enums.h) as
ASSET_<hex id>_<NAME>. Only the names are copied; no game data is involved.

    python3 tools/codegen/gen_bk_asset_names.py path/to/banjo-kazooie/include/enums.h \
        > bridge/src/bk_asset_names.inc
"""
import re
import sys


def main(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    match = re.search(r"enum asset_e\s*\{(.*?)\};", text, re.S)
    if not match:
        sys.exit("enum asset_e not found")

    # Strip comments before splitting: some of them contain commas.
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", match.group(1), flags=re.S)
    # VER_SELECT(usa0, pal, usa1, jp) picks a per-region value; we target US 1.0.
    body = re.sub(r"VER_SELECT\(\s*([^,]+?)\s*,[^)]*\)", r"\1", body)

    names = {}
    next_value = 0
    for raw in body.split(","):
        line = raw.strip()
        if not line:
            continue
        name, _, value = (part.strip() for part in line.partition("="))
        current = int(value, 0) if value else next_value
        next_value = current + 1
        m = re.fullmatch(r"ASSET_([0-9A-Fa-f]+)_(\w+)", name)
        if not m:
            continue
        # The enum value is what the game is compiled with, so it wins over the id in the name.
        if int(m.group(1), 16) != current:
            print(f"warning: {name} has value {current:#x}; using the value", file=sys.stderr)
        if m.group(2).endswith("stub") or m.group(2).endswith("_unk") or m.group(2) == "unk":
            continue
        names[current] = m.group(2)

    print("// Generated by tools/codegen/gen_bk_asset_names.py from the CC0 Banjo-Kazooie")
    print("// decompilation (include/enums.h, enum asset_e). Do not edit by hand.")
    for asset_id in sorted(names):
        print(f'{{0x{asset_id:04X}, "{names[asset_id]}"}},')


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
